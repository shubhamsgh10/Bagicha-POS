/**
 * Generates shared/print/kotGlyphs.ts — the glyph outlines the image-style KOT is drawn from.
 *
 * WHY a generated table instead of a font file: the KOT is drawn on the SERVER (Vercel function or the
 * Electron host's bundled server) as a 1-bit bitmap, because the thermal printer's built-in font is fixed
 * and cannot be a proportional face like the Petpooja-style ticket. Shipping outlines as plain data means no
 * runtime font library, no fs reads of a font file (which Vercel's file tracing and the packaged Electron
 * build can both miss) and identical output everywhere.
 *
 * Source: DejaVu Sans (Regular + Bold) via @fontsource/dejavu-sans — the closest open-licensed match to the
 * Verdana-like face on the reference ticket. opentype.js is a devDependency used ONLY by this script.
 *
 * Run: node scripts/gen-kot-glyphs.mjs      (re-run only to change the charset / weights; commit the output)
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const FILES = {
  regular: "node_modules/@fontsource/dejavu-sans/files/dejavu-sans-latin-400-normal.woff",
  bold: "node_modules/@fontsource/dejavu-sans/files/dejavu-sans-latin-700-normal.woff",
};

// Printable ASCII + the few typographic extras a menu item name / note can plausibly contain.
// A character outside this set makes the generator fall back to the plain-text KOT (see kotImage.ts).
const EXTRA = "×–—‘’“”•…½¼¾°·»«";
const CHARSET = Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => String.fromCharCode(0x20 + i)).concat(Array.from(EXTRA));

function load(rel) {
  const buf = readFileSync(join(root, rel));
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
}

function pathData(commands) {
  let out = "";
  for (const c of commands) {
    const n = (v) => String(Math.round(v));
    if (c.type === "M") out += `M${n(c.x)} ${n(c.y)}`;
    else if (c.type === "L") out += `L${n(c.x)} ${n(c.y)}`;
    else if (c.type === "Q") out += `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
    else if (c.type === "C") out += `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
    else if (c.type === "Z") out += "Z";
  }
  return out;
}

function extract(font) {
  const glyphs = {};
  for (const ch of CHARSET) {
    const g = font.charToGlyph(ch);
    if (!g || g.index === 0) continue; // .notdef — the face doesn't have it
    glyphs[ch] = [Math.round(g.advanceWidth), ch === " " ? "" : pathData(g.path.commands)];
  }
  const os2 = font.tables.os2 ?? {};
  return {
    upm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    capHeight: os2.sCapHeight ?? Math.round(font.unitsPerEm * 0.73),
    xHeight: os2.sxHeight ?? Math.round(font.unitsPerEm * 0.55),
    glyphs,
  };
}

const data = { regular: extract(load(FILES.regular)), bold: extract(load(FILES.bold)) };

const header = `/**
 * GENERATED by scripts/gen-kot-glyphs.mjs — do not edit by hand.
 *
 * Glyph outlines of DejaVu Sans (Regular, Bold) for the image-style KOT (shared/print/kotImage.ts).
 * Coordinates are font units, y-up; \`path\` is SVG-style path data (M L Q C Z, absolute, integers).
 *
 * DejaVu Sans: Copyright (c) 2003 Bitstream, Inc.; changes by Tavmjong Bah and the DejaVu authors are public
 * domain. Free to use, copy and embed under the Bitstream Vera licence: https://dejavu-fonts.github.io/License.html
 */
`;
const body =
  `export interface KotFace {\n  upm: number;\n  ascender: number;\n  descender: number;\n  capHeight: number;\n  xHeight: number;\n` +
  `  /** char -> [advance, path data] */\n  glyphs: Record<string, [number, string]>;\n}\n\n` +
  `export const KOT_FACES: { regular: KotFace; bold: KotFace } = ${JSON.stringify(data)};\n`;

writeFileSync(join(root, "shared/print/kotGlyphs.ts"), header + body);
for (const k of Object.keys(data)) {
  console.log(k, "glyphs:", Object.keys(data[k].glyphs).length, "upm:", data[k].upm);
}
