/** Existing item: rows → menu_items id + its CURRENT name (as stored, spaces aside). */
const u = (rows: number[], id: number, name: string, price: number, rename?: string): Target =>
  ({ kind: "update", rows, id, name, price, ...(rename ? { rename } : {}) });
/** Existing pizza: its Small / Medium / Large PDF rows, in that order. */
const s = (rows: [number, number, number], id: number, name: string, Small: number, Medium: number, Large: number): Target =>
  ({ kind: "sizes", rows, id, name, sizes: { Small, Medium, Large } });
/** New dish in an existing category (id + name, both checked against the live table). */
const n = (rows: number[], name: string, categoryId: number, category: string, price: number): Target =>
  ({ kind: "new", rows, name, categoryId, category, price });

